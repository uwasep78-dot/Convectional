export function t(key, lang = 'en', params = {}) {
  const keys = key.split('.')
  let obj = T[lang] || T.en
  for (const k of keys) {
    if (obj == null || typeof obj !== 'object') return key
    obj = obj[k]
  }
  let result = typeof obj === 'string' ? obj : key
  result = result.replace(/\{(\w+)\}/g, (_, p) => params[p] !== undefined ? params[p] : `{${p}}`)
  return result
}

